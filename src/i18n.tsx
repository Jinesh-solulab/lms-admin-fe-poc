const DICT: Record<Lang, Record<TKey, string>> = { en, ar, ur };
const LANG_KEY = 'hs_admin_lang';

/** Arabic and Urdu are both right-to-left. */
export const isRtl = (l: Lang) => l === 'ar' || l === 'ur';

/** Translation key for a language's name, e.g. for the rider language column. */
export const LANG_NAME_KEY: Record<Lang, TKey> = { en: 'lang.en', ar: 'lang.ar', ur: 'lang.ur' };

/** Each language in its own script, for the language switch. */
export const LANG_NATIVE: Record<Lang, string> = { en: 'English', ar: 'العربية', ur: 'اردو' };

function savedLang(): Lang {
  try {
    const v = localStorage.getItem(LANG_KEY);
    if (v === 'ar' || v === 'en' || v === 'ur') return v;
  } catch {
    /* storage blocked */
  }
  return 'en';
}

interface I18nState {
  lang: Lang;
  dir: 'ltr' | 'rtl';
  setLang: (l: Lang) => void;
  t: (key: TKey, params?: Record<string, string | number>) => string;
  /** Pick the UI language from an { en, ar, ur } value. Fallback: English, then Arabic (same rule as the backend). */
  pick: (v?: Partial<Localized> | null) => string;
}

const I18nContext = createContext<I18nState | null>(null);

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(savedLang);
  const dir = isRtl(lang) ? 'rtl' : 'ltr';

  // Set before children render so the very first API call already sends the right Accept-Language.
  session.setLang(lang);

  useEffect(() => {
    document.documentElement.lang = lang;
    document.documentElement.dir = dir;
    dayjs.locale(lang);
    try {
      localStorage.setItem(LANG_KEY, lang);
    } catch {
      /* storage blocked */
    }
  }, [lang, dir]);

  const setLang = useCallback((l: Lang) => setLangState(l), []);

  const t = useCallback(
    (key: TKey, params?: Record<string, string | number>) => {
      let s = DICT[lang][key] ?? en[key] ?? key;
      if (params) for (const [k, v] of Object.entries(params)) s = s.split(`{${k}}`).join(String(v));
      return s;
    },
    [lang],
  );

  const pick = useCallback(
    (v?: Partial<Localized> | null) => (v ? v[lang] || v.en || v.ar || v.ur || '' : ''),
    [lang],
  );

  const value = useMemo(() => ({ lang, dir: dir as 'ltr' | 'rtl', setLang, t, pick }), [lang, dir, setLang, t, pick]);
  return <I18nContext.Provider value={value}>{children}</I18nContext.Provider>;
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used inside I18nProvider');
  return ctx;
}
